// Bundles the official Capacitor plugin API into one ES module the static website can load:
// ../native/vendor/capacitor-auth.js (committed - the website has no build step of its own).
//
//   npm run build:native
//
// Run again after upgrading @capacitor/core. The website loads this file only inside the Android app
// (firebase-backend.js, signIn; native/episode-alerts.js), never in a browser.
import { build } from 'esbuild';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const outfile = join(HERE, '..', '..', 'native', 'vendor', 'capacitor-auth.js');

await build({
  entryPoints: [join(HERE, 'native-entry.js')],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  legalComments: 'inline',
  banner: {
    js: '// Generated by android-app/scripts/build-native.mjs from @capacitor/core. Do not edit.',
  },
  outfile,
});
console.log(`wrote ${outfile}`);
